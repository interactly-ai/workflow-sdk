"""
Type-safe config classes re-exported from ``interactly-configs``.

Available when the SDK is installed with the ``configs`` extra::

    pip install "interactly[configs]"

Usage::

    from interactly.configs import (
        WorkflowConfig,
        BaseNodeConfig,
        EdgeConfig,
        DirectEdgeConfig,
        ConditionalEdgeConfig,
        ToolConfig,
        LLMConfig,
        PromptConfig,
    )

All exported names are the same as those in ``interactly_configs`` — this
module is a convenience facade so callers need only one SDK import path. The
list below is kept exhaustive by ``tests/unit/test_configs_module.py``, which
fails if the two ``__all__`` sets diverge: a facade that silently omits a new
symbol is worse than no facade, because the omission looks like the symbol not
existing.

If ``interactly-configs`` is not installed, importing this module raises an
``ImportError`` with installation instructions.
"""

